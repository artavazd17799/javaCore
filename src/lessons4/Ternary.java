package lessons4;

public class Ternary {
    public static void main(String[] args) {
        int i, k;

        i = 10;
        k = i < 0 ? -i : i; // получить абсолютное
                           // значение переменной
        System.out.println("Абсолютное значение");
        System.out.println(i + " равно " + k);



        k = i < 0 ? -i : i; //получить абсолютное
                             //значение переменной i
        System.out.println("абсолютное значение ");

        System.out.println("абсолютное значение ");
        System.out.println( i + " равно " + k);
    }
}
